/** Quick helper to generate a custom equipment stencil for any U height */
export function createCustomEquipmentStencil(
  uHeight: number,
  label: string,
  category: RackEquipmentStencil['category'] = 'custom',
  color = '#1e293b',
  name?: string
): RackEquipmentStencil {
  const cleanU = Math.max(1, Math.min(12, Math.round(uHeight)));
  const genName = name || `${cleanU}U Custom Equipment (${label})`;
  return {
    id: `custom-${cleanU}u-${Date.now()}-${Math.floor(Math.random() * 1000)}`,
    name: genName,
    defaultLabel: label || `EQ-${cleanU}U`,
    uHeight: cleanU,
    category,
    depthMm: 450,
    color,
    strokeColor: '#38bdf8',
    ports: [{ id: 'p1', type: 'rj45', count: 8, label: 'Ports' }],
    desc: `User configured ${cleanU}U rack equipment with custom front panel designation`,
  };
}
