import { CADObject } from '../../../types/cad';
import { uid } from '../common';

export function buildGeneratorPadBase(
  w: number,
  h: number,
  padMargin: number,
  encW: number,
  encH: number
): CADObject[] {
  return [
    // 1. Reinforced Concrete Foundation Pad
    {
      id: uid(),
      type: 'rectangle',
      x: 0,
      y: 0,
      width: w,
      height: h,
      stroke: '#94a3b8',
      strokeWidth: 2,
      fill: '#334155',
      fillEnabled: true,
      fillOpacity: 0.9,
      opacity: 1,
    },
    // Corner Anchor Bolt Plates
    ...[
      { x: 3, y: 3 },
      { x: w - 9, y: 3 },
      { x: 3, y: h - 9 },
      { x: w - 9, y: h - 9 },
    ].map((pt) => ({
      id: uid(),
      type: 'rectangle' as const,
      x: pt.x,
      y: pt.y,
      width: 6,
      height: 6,
      stroke: '#cbd5e1',
      strokeWidth: 1.5,
      fill: '#64748b',
      fillEnabled: true,
      fillOpacity: 1,
      opacity: 1,
    })),
    // 2. Heavy Steel Sub-Base Skid & Fuel Tank Chassis
    {
      id: uid(),
      type: 'rectangle',
      x: padMargin - 3,
      y: padMargin - 3,
      width: encW + 6,
      height: encH + 6,
      stroke: '#0f172a',
      strokeWidth: 2,
      fill: '#18181b',
      fillEnabled: true,
      fillOpacity: 1,
      opacity: 1,
    },
    // Forklift Pockets
    ...[
      { x: padMargin + 26, y: padMargin - 4 },
      { x: padMargin + 64, y: padMargin - 4 },
      { x: padMargin + 26, y: h - padMargin },
      { x: padMargin + 64, y: h - padMargin },
    ].map((pt) => ({
      id: uid(),
      type: 'rectangle' as const,
      x: pt.x,
      y: pt.y,
      width: 16,
      height: 4,
      stroke: '#eab308',
      strokeWidth: 1,
      fill: '#09090b',
      fillEnabled: true,
      fillOpacity: 1,
      opacity: 1,
    })),
    // 3. Acoustic Canopy Body
    {
      id: uid(),
      type: 'rectangle',
      x: padMargin,
      y: padMargin,
      width: encW,
      height: encH,
      stroke: '#22c55e',
      strokeWidth: 2,
      fill: '#166534',
      fillEnabled: true,
      fillOpacity: 1,
      opacity: 1,
    },
    // Beveled Roof Panel Inner Border
    {
      id: uid(),
      type: 'rectangle',
      x: padMargin + 3,
      y: padMargin + 3,
      width: encW - 6,
      height: encH - 6,
      stroke: '#15803d',
      strokeWidth: 1.2,
      fill: 'transparent',
      fillEnabled: false,
      fillOpacity: 0,
      opacity: 0.8,
    },
    // Center Roof Lifting Beam & Eye
    {
      id: uid(),
      type: 'rectangle',
      x: w / 2 - 14,
      y: h / 2 - 4,
      width: 28,
      height: 8,
      stroke: '#86efac',
      strokeWidth: 1.5,
      fill: '#14532d',
      fillEnabled: true,
      fillOpacity: 1,
      opacity: 1,
    },
    {
      id: uid(),
      type: 'circle',
      x: w / 2 - 3,
      y: h / 2 - 3,
      width: 6,
      height: 6,
      stroke: '#ffffff',
      strokeWidth: 1.5,
      fill: '#0f172a',
      fillEnabled: true,
      fillOpacity: 1,
      opacity: 1,
    },
  ];
}
